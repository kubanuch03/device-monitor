"""Под какой учёткой мы идём на устройство.

Отдельная функция, а не поле, потому что ответ зависит от двух объектов сразу:
устройство может пользоваться своей парой логин/пароль, а может - общей парой
точки. Раз мест, где этот вопрос задаётся, три (выдача секрета в браузер, опрос
сведений с железа и признак «есть пароль» в списке), правило обязано быть
одно. Разъедься они - панель показывала бы одно, а опрос ходил бы под другим.

Логин и пароль наследуются ТОЛЬКО парой. Наследовать их по отдельности -
верный способ собрать несуществующую учётку: логин от точки с паролем от
устройства не подойдёт никуда.
"""

from __future__ import annotations

from device_monitor.domain.models import Device, Site


def effective(device: Device, site: Site | None) -> tuple[str, str]:
    """(логин, закодированный пароль). Расшифровку делает вызывающий."""
    if device.use_site_creds and site is not None:
        return site.username, site.password_enc
    return device.username, device.password_enc
